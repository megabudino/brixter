/**
 * Installs the Brixter agent skills into a project.
 *
 * `skills/` holds one canonical, agent-neutral `SKILL.md` per skill. There is no
 * shared skill format across coding agents, so this module is an adapter layer:
 * it reads the canonical source once and emits it in each target agent's own
 * convention — Claude Code skills, Cursor rules, Copilot instructions, Windsurf
 * rules — plus an `AGENTS.md` block, which is the one thing every agent reads.
 *
 * Activation metadata (the globs that make an agent load the right skill for the
 * file it is editing) lives in `skills/skills.json`, not in the SKILL.md
 * frontmatter, so the canonical file stays valid for agents that validate it.
 */
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const SKILLS_DIR = fileURLToPath(new URL('../skills/', import.meta.url));
const PACKAGE_JSON = fileURLToPath(new URL('../package.json', import.meta.url));

const RECEIPT_PATH = '.brixter/skills-install.json';
const AGENTS_SKILLS_DIR = '.brixter/skills';
const BLOCK_START = '<!-- brixter:skills:start -->';
const BLOCK_END = '<!-- brixter:skills:end -->';

const GENERATED_NOTE = (version) =>
	`<!-- Generated by \`brixter skills install\` (brixter v${version}). Edits are overwritten on reinstall. -->`;

// ---------------------------------------------------------------------------
// Targets
// ---------------------------------------------------------------------------

/**
 * One entry per supported agent.
 *
 * `detect` decides whether the project already uses that agent, which is what
 * makes the default install unsurprising: we write for the agents in use, never
 * scatter directories for agents nobody here runs.
 */
const TARGETS = {
	claude: {
		label: 'Claude Code',
		supportsGlobal: true,
		detect: (root) => exists(root, '.claude') || exists(root, 'CLAUDE.md'),
		globalDir: () => path.join(homedir(), '.claude', 'skills'),
		// Claude Code reads SKILL.md verbatim, so this target is a plain copy.
		files: (skill) => [
			{
				path: path.join('.claude', 'skills', skill.name, 'SKILL.md'),
				globalPath: path.join(skill.name, 'SKILL.md'),
				content: skill.source
			}
		]
	},

	cursor: {
		label: 'Cursor',
		supportsGlobal: false,
		detect: (root) => exists(root, '.cursor') || exists(root, '.cursorrules'),
		files: (skill, version) => [
			{
				path: path.join('.cursor', 'rules', `${skill.name}.mdc`),
				content: frontmatter(
					{
						description: skill.description,
						globs: skill.globs.join(','),
						alwaysApply: false
					},
					`${GENERATED_NOTE(version)}\n\n${skill.body}`
				)
			}
		]
	},

	copilot: {
		label: 'GitHub Copilot',
		supportsGlobal: false,
		detect: (root) =>
			exists(root, '.github/copilot-instructions.md') || exists(root, '.github/instructions'),
		files: (skill, version) => [
			{
				path: path.join('.github', 'instructions', `${skill.name}.instructions.md`),
				content: frontmatter(
					{ description: skill.description, applyTo: `"${skill.globs.join(',')}"` },
					`${GENERATED_NOTE(version)}\n\n${skill.body}`
				)
			}
		]
	},

	windsurf: {
		label: 'Windsurf',
		supportsGlobal: false,
		detect: (root) => exists(root, '.windsurf') || exists(root, '.windsurfrules'),
		files: (skill, version) => [
			{
				path: path.join('.windsurf', 'rules', `${skill.name}.md`),
				content: frontmatter(
					{ description: skill.description, trigger: 'glob', globs: skill.globs.join(',') },
					`${GENERATED_NOTE(version)}\n\n${skill.body}`
				)
			}
		]
	},

	/**
	 * The universal floor: Codex, Amp, Zed, OpenCode, Jules and others read
	 * AGENTS.md. It cannot express per-glob activation, so instead of inlining
	 * four long documents we drop the canonical files in the repo and index them
	 * in a managed block — the agent opens the one it needs.
	 */
	agents: {
		label: 'AGENTS.md (Codex, Amp, Zed, OpenCode, …)',
		supportsGlobal: false,
		detect: (root) => exists(root, 'AGENTS.md'),
		files: (skill, version) => [
			{
				path: path.join(AGENTS_SKILLS_DIR, skill.name, 'SKILL.md'),
				content: `${GENERATED_NOTE(version)}\n\n${skill.source}`
			}
		],
		// Applied once after the per-skill files, not per skill.
		finalize: agentsMdBlock
	}
};

// ---------------------------------------------------------------------------
// Commands
// ---------------------------------------------------------------------------

export async function installSkills({ cwd, agents, global: isGlobal, force, dryRun, quiet }) {
	const root = path.resolve(cwd);
	const version = await packageVersion();
	const skills = await loadSkills();
	const names = resolveTargets(agents, root, isGlobal);

	if (names.length === 0) {
		throw new Error(
			'no install target resolved. Pass --agent <claude|cursor|copilot|windsurf|agents|all>.'
		);
	}

	const receipt = await readReceipt(root);
	const written = [];
	const skipped = [];

	for (const name of names) {
		const target = TARGETS[name];
		const useGlobal = isGlobal && target.supportsGlobal;
		const base = useGlobal ? target.globalDir() : root;

		for (const skill of skills) {
			for (const file of target.files(skill, version)) {
				const relative = useGlobal ? file.globalPath : file.path;
				const absolute = path.join(base, relative);
				const key = useGlobal ? path.join(base, relative) : relative;

				if (!force && (await isUserModified(absolute, receipt.files?.[key]))) {
					skipped.push({ key, reason: 'modified since install — rerun with --force' });
					continue;
				}
				if (!dryRun) await writeFileEnsured(absolute, file.content);
				written.push({ key, absolute, content: file.content, target: name });
			}
		}

		if (target.finalize && !useGlobal) {
			const extra = await target.finalize({ root, skills, version, dryRun });
			if (extra) written.push(extra);
		}
	}

	if (!dryRun) {
		// Merged, not replaced: installing one target must not erase what we know
		// about the others, or their files lose modification protection and drop
		// out of `skills status`.
		await writeReceipt(root, {
			version,
			targets: [...new Set([...(receipt.targets ?? []), ...names])],
			global: Boolean(isGlobal),
			files: {
				...receipt.files,
				...Object.fromEntries(written.map((f) => [f.key, hash(f.content)]))
			}
		});
	}

	if (quiet) reportQuiet({ written, skipped, version });
	else report({ names, written, skipped, dryRun, isGlobal, version });

	return { written, skipped, version };
}

export async function listSkills() {
	const skills = await loadSkills();
	process.stdout.write(`Brixter agent skills\n\n`);
	for (const skill of skills) {
		process.stdout.write(`  ${skill.name}\n`);
		process.stdout.write(`    ${wrap(skill.description, 74, '    ')}\n`);
		process.stdout.write(`    applies to: ${skill.globs.join(', ')}\n\n`);
	}
	process.stdout.write(`Targets: ${Object.keys(TARGETS).join(', ')}\n`);
}

export async function skillsStatus({ cwd }) {
	const root = path.resolve(cwd);
	const version = await packageVersion();
	const receipt = await readReceipt(root);

	if (!receipt.version) {
		process.stdout.write(
			`No Brixter skills installed in ${root}\nRun \`npx brixter skills install\`.\n`
		);
		return;
	}

	process.stdout.write(`Installed from brixter v${receipt.version}`);
	process.stdout.write(
		receipt.version === version
			? ` (current)\n`
			: ` — package is now v${version}. Rerun \`npx brixter skills install\` to refresh.\n`
	);
	process.stdout.write(`Targets: ${(receipt.targets ?? []).join(', ')}\n\n`);

	for (const [relative, expected] of Object.entries(receipt.files ?? {})) {
		const absolute = path.isAbsolute(relative) ? relative : path.join(root, relative);
		let state = 'ok';
		if (!existsSync(absolute)) state = 'missing';
		else if (hash(await readFile(absolute, 'utf8')) !== expected) state = 'locally modified';
		process.stdout.write(`  ${state.padEnd(17)} ${relative}\n`);
	}
}

// ---------------------------------------------------------------------------
// Skill loading
// ---------------------------------------------------------------------------

async function loadSkills() {
	const manifest = JSON.parse(await readFile(path.join(SKILLS_DIR, 'skills.json'), 'utf8'));
	const entries = manifest.skills ?? [];

	const known = new Set(entries.map((entry) => entry.dir));
	const onDisk = (await readdir(SKILLS_DIR, { withFileTypes: true }))
		.filter((d) => d.isDirectory())
		.map((d) => d.name);
	const orphans = onDisk.filter((dir) => !known.has(dir));
	if (orphans.length > 0) {
		// A skill directory nobody lists would silently never install.
		throw new Error(`skills/skills.json does not list: ${orphans.join(', ')}`);
	}

	return Promise.all(
		entries.map(async (entry) => {
			const source = await readFile(path.join(SKILLS_DIR, entry.dir, 'SKILL.md'), 'utf8');
			return {
				name: entry.name,
				description: entry.description,
				globs: entry.globs ?? [],
				entry: Boolean(entry.entry),
				source,
				body: stripFrontmatter(source)
			};
		})
	);
}

function stripFrontmatter(source) {
	return source.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, '').trimStart();
}

function frontmatter(fields, body) {
	const lines = Object.entries(fields)
		.filter(([, value]) => value !== undefined && value !== '')
		.map(([key, value]) => `${key}: ${value}`);
	return `---\n${lines.join('\n')}\n---\n\n${body}`;
}

// ---------------------------------------------------------------------------
// AGENTS.md managed block
// ---------------------------------------------------------------------------

async function agentsMdBlock({ root, skills, version, dryRun }) {
	const file = path.join(root, 'AGENTS.md');
	const existing = existsSync(file) ? await readFile(file, 'utf8') : '';

	const rows = skills
		.map(
			(skill) =>
				`| \`${skill.globs.join('`, `')}\` | [\`${AGENTS_SKILLS_DIR}/${skill.name}/SKILL.md\`](./${AGENTS_SKILLS_DIR}/${skill.name}/SKILL.md) | ${skill.description} |`
		)
		.join('\n');

	const entrySkill = skills.find((skill) => skill.entry) ?? skills[0];

	const block = [
		BLOCK_START,
		`<!-- Managed by \`brixter skills install\` (brixter v${version}). Edit skills/ in the brixter package, not this block. -->`,
		'',
		'## Brixter',
		'',
		'This project builds its pages with [Brixter](https://github.com/Brixter-Labs/brixter):',
		'content lives in the repo as `+page.md` pages and `.brix` sections, compiled at',
		'build time. Before creating or editing one of the files below, **read the linked',
		'guide first** — the annotation syntax is specific and failures are silent.',
		'',
		'| When you touch | Read | What it covers |',
		'| --- | --- | --- |',
		rows,
		'',
		`Starting from scratch, or unsure which applies? Read [\`${AGENTS_SKILLS_DIR}/${entrySkill.name}/SKILL.md\`](./${AGENTS_SKILLS_DIR}/${entrySkill.name}/SKILL.md).`,
		BLOCK_END
	].join('\n');

	const next = replaceBlock(existing, block);
	if (!dryRun) await writeFileEnsured(file, next);
	return { key: 'AGENTS.md', absolute: file, content: next, target: 'agents' };
}

function replaceBlock(existing, block) {
	const start = existing.indexOf(BLOCK_START);
	const end = existing.indexOf(BLOCK_END);

	if (start !== -1 && end !== -1 && end > start) {
		return existing.slice(0, start) + block + existing.slice(end + BLOCK_END.length);
	}
	if (existing.trim() === '') return `${block}\n`;
	return `${existing.replace(/\s*$/, '')}\n\n${block}\n`;
}

// ---------------------------------------------------------------------------
// Target resolution + reporting
// ---------------------------------------------------------------------------

function resolveTargets(requested, root, isGlobal) {
	if (requested) {
		const names = requested === 'all' ? Object.keys(TARGETS) : splitList(requested);
		const unknown = names.filter((name) => !TARGETS[name]);
		if (unknown.length > 0) {
			throw new Error(
				`unknown target(s): ${unknown.join(', ')}. Known: ${Object.keys(TARGETS).join(', ')}`
			);
		}
		return names;
	}

	// A global install only makes sense for targets that have a user-level
	// directory; defaulting to project-scoped ones there would write into $HOME.
	if (isGlobal) return Object.keys(TARGETS).filter((name) => TARGETS[name].supportsGlobal);

	const detected = Object.keys(TARGETS).filter(
		(name) => name !== 'agents' && TARGETS[name].detect(root)
	);
	return [...detected, 'agents'];
}

function splitList(value) {
	return value
		.split(',')
		.map((entry) => entry.trim())
		.filter(Boolean);
}

/**
 * The postinstall voice: a couple of lines in someone else's `npm install`
 * output. Silence when nothing changed, and name the skipped files, since those
 * are the ones still carrying stale guidance.
 */
function reportQuiet({ written, skipped, version }) {
	if (written.length === 0 && skipped.length === 0) return;

	process.stdout.write(`brixter: refreshed ${written.length} agent skill file(s) → v${version}\n`);
	if (skipped.length > 0) {
		process.stdout.write(
			`brixter: kept ${skipped.length} locally modified file(s) — ` +
				`run \`npx brixter skills install --force\` to overwrite:\n`
		);
		for (const file of skipped) process.stdout.write(`  ${file.key}\n`);
	}
}

function report({ names, written, skipped, dryRun, isGlobal, version }) {
	const verb = dryRun ? 'Would write' : 'Wrote';
	const scope = isGlobal ? 'user-level' : 'project';

	process.stdout.write(
		`Brixter skills v${version} → ${names.map((n) => TARGETS[n].label).join(', ')} (${scope})\n\n`
	);
	for (const file of written) process.stdout.write(`  ${verb.toLowerCase()}  ${file.key}\n`);

	for (const file of skipped) {
		process.stdout.write(`  skipped  ${file.key} — ${file.reason}\n`);
	}

	if (written.length > 0 && !dryRun) {
		process.stdout.write(
			`\n${written.length} file(s) written. Commit them so the whole team's agents pick them up.\n`
		);
	}
	if (names.includes('claude') && !isGlobal) {
		process.stdout.write(`Claude Code loads project skills on the next session.\n`);
	}
	if (isGlobal) {
		const excluded = Object.keys(TARGETS).filter((n) => !TARGETS[n].supportsGlobal);
		process.stdout.write(
			`\nNote: ${excluded.join(', ')} have no user-level rules directory — install those per project.\n`
		);
	}
}

// ---------------------------------------------------------------------------
// Files
// ---------------------------------------------------------------------------

async function writeFileEnsured(absolute, content) {
	await mkdir(path.dirname(absolute), { recursive: true });
	await writeFile(absolute, content.endsWith('\n') ? content : `${content}\n`, 'utf8');
}

/**
 * A file counts as user-modified only if it exists, we installed it before, and
 * its content no longer matches what we wrote. A file we never installed is
 * overwritten — it is ours by name — and an unchanged one is refreshed silently.
 */
async function isUserModified(absolute, expectedHash) {
	if (!expectedHash || !existsSync(absolute)) return false;
	const current = await readFile(absolute, 'utf8');
	return hash(current) !== expectedHash;
}

function hash(content) {
	return createHash('sha256')
		.update(content.endsWith('\n') ? content : `${content}\n`)
		.digest('hex')
		.slice(0, 16);
}

async function readReceipt(root) {
	const file = path.join(root, RECEIPT_PATH);
	if (!existsSync(file)) return {};
	try {
		return JSON.parse(await readFile(file, 'utf8'));
	} catch {
		return {};
	}
}

async function writeReceipt(root, receipt) {
	await writeFileEnsured(path.join(root, RECEIPT_PATH), `${JSON.stringify(receipt, null, 2)}\n`);
}

async function packageVersion() {
	return JSON.parse(await readFile(PACKAGE_JSON, 'utf8')).version;
}

function exists(root, relative) {
	return existsSync(path.join(root, relative));
}

function wrap(text, width, indent) {
	const words = text.split(/\s+/);
	const lines = [];
	let line = '';
	for (const word of words) {
		if (line.length + word.length + 1 > width) {
			lines.push(line);
			line = word;
		} else {
			line = line ? `${line} ${word}` : word;
		}
	}
	if (line) lines.push(line);
	return lines.join(`\n${indent}`);
}
